def print_experiment_summary(config: Dict) -> None:
    """
    Print the mandatory experiment configuration header before any evaluation.

    This block must appear at the top of every evaluation log to ensure
    reproducibility and prevent ambiguity about experimental conditions.

    Parameters
    ----------
    config : dict
        Expected keys (all optional – sensible defaults are shown):

        - ``dataset``       : str   (default: "VisDrone2019-DET")
        - ``split``         : str   (default: "test")
        - ``n_images``      : int   total images evaluated
        - ``n_gt_objects``  : int   total ground-truth objects
        - ``gt_source``     : str   (default: "VisDrone original annotations")
        - ``classes``       : int   (default: 10)
        - ``class_names``   : list  (default: VisDrone names)
        - ``image_size``    : str   (default: "640×640")
        - ``iou_threshold`` : float (default: 0.50)
        - ``conf_threshold``: float (default: 0.25)
        - ``model``         : str   model name / checkpoint path
        - ``extra``         : dict  any additional key-value pairs

    Example output::

        ================================================
        EXPERIMENT CONFIGURATION
        ================================================
        Dataset              : VisDrone2019-DET
        Split                : test
        Total Images         : 548
        Total GT Objects     : 39987
        GT Source            : VisDrone original annotations
        Classes              : 10 (pedestrian, people, ...)
        Image Size           : 640×640
        IoU Threshold        : 0.50
        Confidence Threshold : 0.25
        ================================================
    """
    from visdrone_parser import CLASS_NAMES  # local import to avoid circulars

    sep  = "=" * 56
    sep2 = "-" * 56

    dataset       = config.get("dataset",       "VisDrone2019-DET")
    split         = config.get("split",         "test")
    n_images      = config.get("n_images",      "N/A")
    n_gt          = config.get("n_gt_objects",  "N/A")
    gt_source     = config.get("gt_source",     "VisDrone original annotations")
    n_classes     = config.get("classes",       10)
    class_names   = config.get("class_names",   CLASS_NAMES)
    image_size    = config.get("image_size",    "640×640")
    iou_thresh    = config.get("iou_threshold", 0.50)
    conf_thresh   = config.get("conf_threshold",0.25)
    model         = config.get("model",         None)
    extra         = config.get("extra",         {})

    class_str = ", ".join(class_names[:3]) + " ..." if len(class_names) > 3 else ", ".join(class_names)

    lines = [
        sep,
        "EXPERIMENT CONFIGURATION",
        sep,
        f"{'Dataset':<22}: {dataset}",
        f"{'Split':<22}: {split}",
        f"{'Total Images':<22}: {n_images}",
        f"{'Total GT Objects':<22}: {n_gt}",
        f"{'GT Source':<22}: {gt_source}",
        f"{'Classes':<22}: {n_classes} ({class_str})",
        f"{'Image Size':<22}: {image_size}",
        f"{'IoU Threshold':<22}: {iou_thresh:.2f}",
        f"{'Confidence Threshold':<22}: {conf_thresh:.2f}",
    ]

    if model:
        lines.append(f"{'Model':<22}: {model}")

    if extra:
        lines.append(sep2)
        for k, v in extra.items():
            lines.append(f"  {k:<20}: {v}")

    lines.append(sep)

    for line in lines:
        print(line)
    logger.info("Experiment summary printed.")
