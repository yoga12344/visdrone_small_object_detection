"""
dataset_validator.py
Data leakage prevention and dataset integrity checks for the VisDrone
hackathon pipeline.

All checks are designed to be run BEFORE any training or evaluation to
ensure scientific rigour and prevent contamination of results.
"""

import logging
import math
from collections import Counter
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Expected VisDrone class distribution (approximate, derived from the official
# VisDrone2019-DET training set statistics).
# Used as a sanity-check baseline; large deviations suggest a corrupt or
# re-labelled dataset.
# ---------------------------------------------------------------------------
_EXPECTED_DISTRIBUTION: Dict[str, Tuple[float, float]] = {
    # class_name : (min_pct, max_pct)  — generous bounds
    "car":               (25.0, 50.0),
    "pedestrian":        (10.0, 35.0),
    "people":            (5.0,  25.0),
    "motor":             (3.0,  20.0),
    "van":               (2.0,  15.0),
    "truck":             (1.0,  10.0),
    "tricycle":          (0.5,  10.0),
    "awning-tricycle":   (0.2,   8.0),
    "bus":               (0.2,   8.0),
    "bicycle":           (0.2,   8.0),
}


# ---------------------------------------------------------------------------
# Pseudo-GT detection
# ---------------------------------------------------------------------------


def check_no_pseudo_gt(labels_dir: str) -> Tuple[bool, str]:
    """
    Verify that labels were **not** generated by a model (pseudo-labels).

    Heuristic checks performed:

    1. **Annotation density** – model detections on VisDrone are typically
       sparse (< 5 objects / image on average at standard confidence).
       Real GT files average ~12 objects / image in VisDrone.
    2. **Coordinate precision** – VisDrone GT coordinates are integers.
       Model outputs are floating-point normalised values with many
       non-zero decimal places.
    3. **Empty file ratio** – models produce many empty files for
       uneventful frames; real GT has < 2 % empty files.

    Parameters
    ----------
    labels_dir : str
        Directory containing YOLO-format ``.txt`` label files.

    Returns
    -------
    is_valid : bool
        ``True`` if the labels appear to be genuine ground-truth.
    warning_message : str
        Human-readable summary of findings.
    """
    labels_dir = Path(labels_dir)
    if not labels_dir.exists():
        return False, f"Labels directory does not exist: {labels_dir}"

    label_files = list(labels_dir.glob("*.txt"))
    if not label_files:
        return False, "No .txt label files found – cannot validate."

    total_files   = len(label_files)
    empty_files   = 0
    total_objects = 0
    coord_integer_count = 0
    coord_total         = 0

    for lf in label_files:
        lines = [l.strip() for l in lf.read_text(encoding="utf-8").splitlines() if l.strip()]
        if not lines:
            empty_files += 1
            continue

        total_objects += len(lines)
        for line in lines:
            parts = line.split()
            if len(parts) != 5:
                continue
            try:
                coords = [float(p) for p in parts[1:]]
            except ValueError:
                continue
            coord_total += len(coords)
            for c in coords:
                # Check if the value is a clean multiple of 1/image_dim
                # Real GT: coords derived from integer pixels tend to have
                # at most ~4-5 significant decimal places.
                fractional_part = abs(c - round(c, 4))
                if fractional_part < 1e-5:
                    coord_integer_count += 1

    warnings: List[str] = []
    is_valid = True

    # Check 1 – average annotation density
    avg_objects = total_objects / max(total_files - empty_files, 1)
    if avg_objects < 3.0:
        warnings.append(
            f"LOW annotation density: {avg_objects:.1f} objects/image "
            f"(expected ≥ 12 for real VisDrone GT). "
            "This is consistent with sparse model outputs."
        )
        is_valid = False
    else:
        logger.debug("Annotation density OK: %.1f objects/image.", avg_objects)

    # Check 2 – empty file ratio
    empty_ratio = empty_files / total_files
    if empty_ratio > 0.05:
        warnings.append(
            f"HIGH empty-file ratio: {empty_ratio:.1%} "
            f"({empty_files}/{total_files} files). "
            "Real VisDrone GT has < 2 % empty files."
        )
        is_valid = False

    # Check 3 – coordinate precision
    if coord_total > 0:
        precision_ratio = coord_integer_count / coord_total
        if precision_ratio < 0.7:
            warnings.append(
                f"LOW coordinate precision: only {precision_ratio:.1%} of "
                "coordinate values look like integer-derived GT. "
                "Floating-point heavy values suggest model-generated labels."
            )
            is_valid = False

    if not warnings:
        msg = (
            f"Labels appear genuine: {avg_objects:.1f} obj/img, "
            f"{empty_ratio:.1%} empty files, coordinate precision OK."
        )
    else:
        msg = "POTENTIAL PSEUDO-GT DETECTED:\n  " + "\n  ".join(warnings)

    return is_valid, msg


# ---------------------------------------------------------------------------
# Train / test overlap
# ---------------------------------------------------------------------------


def check_train_test_overlap(
    train_image_ids: List[str],
    test_image_ids: List[str],
) -> Tuple[int, List[str]]:
    """
    Check for overlap between train and test image IDs.

    Any overlap constitutes data leakage and must be resolved before
    training or evaluation.

    Parameters
    ----------
    train_image_ids : list of str
        Image IDs (file stems) in the training split.
    test_image_ids : list of str
        Image IDs (file stems) in the test / validation split.

    Returns
    -------
    overlap_count : int
        Number of overlapping IDs (0 = clean split).
    overlap_ids : list of str
        The overlapping image IDs.
    """
    train_set: Set[str] = set(train_image_ids)
    test_set:  Set[str] = set(test_image_ids)
    overlap = sorted(train_set & test_set)

    if overlap:
        logger.error(
            "DATA LEAKAGE: %d image(s) appear in both train and test sets!",
            len(overlap),
        )
        for oid in overlap[:10]:
            logger.error("  Overlap: %s", oid)
        if len(overlap) > 10:
            logger.error("  ... and %d more.", len(overlap) - 10)
    else:
        logger.info("Train/test split is clean – no overlapping image IDs.")

    return len(overlap), overlap


# ---------------------------------------------------------------------------
# Class distribution check
# ---------------------------------------------------------------------------


def check_class_distribution(
    gt_annotations: List[Dict],
    expected: Optional[Dict[str, Tuple[float, float]]] = None,
) -> Dict:
    """
    Verify that the class distribution matches VisDrone expectations.

    VisDrone is heavily skewed toward ``car`` and ``pedestrian``; a flat or
    reversed distribution indicates a problem with the dataset or parsing.

    Parameters
    ----------
    gt_annotations : list of dict
        Annotation dicts as returned by ``parse_visdrone_annotation``.
        Ignored-region entries (class_id == -1) are excluded automatically.
    expected : dict, optional
        Override the built-in expected distribution bounds.
        Keys are class names; values are ``(min_pct, max_pct)`` tuples.

    Returns
    -------
    dict
        - ``counts``       : ``{class_name: int}``
        - ``percentages``  : ``{class_name: float}``
        - ``warnings``     : list of warning strings
        - ``is_valid``     : bool
    """
    if expected is None:
        expected = _EXPECTED_DISTRIBUTION

    valid_anns = [a for a in gt_annotations if a.get("class_id", -1) >= 0]
    counts = Counter(a["class_name"] for a in valid_anns)
    total  = max(sum(counts.values()), 1)

    percentages = {cls: (counts.get(cls, 0) / total * 100) for cls in expected}
    warnings: List[str] = []

    for cls_name, (lo, hi) in expected.items():
        pct = percentages.get(cls_name, 0.0)
        if not (lo <= pct <= hi):
            warnings.append(
                f"Class '{cls_name}': {pct:.1f}% (expected {lo:.1f}–{hi:.1f}%)"
            )

    is_valid = len(warnings) == 0

    if warnings:
        logger.warning("Class distribution anomalies detected:")
        for w in warnings:
            logger.warning("  %s", w)
    else:
        logger.info("Class distribution within expected bounds.")

    return {
        "counts":      dict(counts),
        "percentages": percentages,
        "warnings":    warnings,
        "is_valid":    is_valid,
    }


# ---------------------------------------------------------------------------
# Experiment summary printer
